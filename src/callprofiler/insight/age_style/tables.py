def year_range_to_group_dist(birth_low: int, birth_high: int,
                              reference_year: int | None = None) -> dict:
    """Т2: интервал года рождения -> P(g) через перекрытие с возрастными
    границами групп на reference_year (по умолчанию — текущий год)."""
    ref = reference_year or datetime.date.today().year
    age_low = ref - birth_high
    age_high = ref - birth_low
    overlaps = {}
    for g in GROUP_CODES:
        glo, ghi = GROUP_RANGES[g]
        overlaps[g] = max(0, min(age_high, ghi) - max(age_low, glo) + 1)
    total = sum(overlaps.values())
    if total <= 0:
        return uniform_dist()
    return {g: v / total for g, v in overlaps.items()}


